// Build a minimal WorkbookData from a CSV string for demo loading
export function buildWorkbookFromCsv(
  fileName: string,
  csv: string,
  sheetName = 'Sheet1'
): WorkbookData {
  const lines = csv.split(/\r?\n/).filter((l) => l.trim() !== '');
  const rows: string[][] = lines.map((line) => {
    const out: string[] = [];
    let cur = '';
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (inQuotes) {
        if (ch === '"' && line[i + 1] === '"') {
          cur += '"';
          i++;
        } else if (ch === '"') {
          inQuotes = false;
        } else {
          cur += ch;
        }
      } else {
        if (ch === ',') {
          out.push(cur);
          cur = '';
        } else if (ch === '"') {
          inQuotes = true;
        } else {
          cur += ch;
        }
      }
    }
    out.push(cur);
    return out;
  });
  const sheet: SheetData = {
    name: sheetName,
    rows: rows.map((r) => r.map((c) => (c === '' ? null : c))),
    rowCount: rows.length,
    colCount: rows.length > 0 ? Math.max(...rows.map((r) => r.length)) : 0,
  };
  return {
    fileName,
    fileSize: csv.length,
    sheetNames: [sheetName],
    sheets: { [sheetName]: sheet },
  };
}
